/// `Boid::steerToFlock` without obstacles: weighted sum of the three normalized forces.
fn steer_to_flock(v: &Vehicle, others: &[&Vehicle]) -> Vec2 {
    let others = || others.iter().copied();
    separation(v, 5.0, -0.707, others()) * 12.0
        + alignment(v, 7.5, 0.7, others()) * 8.0
        + cohesion(v, 9.0, -0.15, others()) * 8.0
}

/// `sphericalWrapAround` on the ground: leaving the circle reenters on the opposite side.
fn wrap_around(p: Vec2, radius: f32) -> Vec2 {
    let r = p.length();
    if r > radius {
        p + (p / r) * radius * -2.0
    } else {
        p
    }
}

#[test]
fn boids_match_cpp() {
    let mut boids: Vec<Vehicle> = (0..12)
        .map(|i| {
            let (a, r, h) = (i as f32 * 0.7, 2.0 + i as f32 * 0.8, i as f32 * 1.3);
            Vehicle {
                position: Vec2::new(r * a.cos(), r * a.sin()),
                forward: Vec2::new(h.cos(), h.sin()),
                speed: 9.0 * 0.3,
                max_force: 27.0,
                max_speed: 9.0,
                ..Vehicle::default()
            }
        })
        .collect();
    let mut checkpoints = BOIDS.iter();
    for step in 1..=600 {
        for i in 0..boids.len() {
            let others: Vec<&Vehicle> = boids
                .iter()
                .enumerate()
                .filter_map(|(j, b)| (j != i).then_some(b))
                .collect();
            let force = steer_to_flock(&boids[i], &others);
            boids[i].apply_steering_force(force, 1.0 / 60.0);
            boids[i].position = wrap_around(boids[i].position, 50.0);
        }
        if step % 100 != 0 {
            continue;
        }
        for _ in 0..boids.len() {
            let &(s, i, px, py, fx, fy, speed) = checkpoints.next().unwrap();
            let b = &boids[i];
            let got = [
                b.position.x,
                b.position.y,
                b.forward.x,
                b.forward.y,
                b.speed,
            ];
            let want = [px, py, fx, fy, speed];
            for (g, w) in got.iter().zip(want) {
                assert!(
                    (f64::from(*g) - w).abs() < 1e-4,
                    "step {s} boid {i}: got {got:?}, want {want:?}"
                );
            }
        }
    }
}
