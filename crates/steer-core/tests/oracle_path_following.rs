fn check(directed: bool, start: Vec2, expected: &[Checkpoint]) {
    let points: Vec<Vec2> = EIGHT.iter().map(|&(x, y)| Vec2::new(x, y)).collect();
    let path = Pathway::new(&points, 2.0, false);
    let mut v = Vehicle {
        position: start,
        max_speed: 2.0,
        max_force: 8.0,
        radius: 0.5,
        ..Vehicle::default()
    };
    let mut direction = 1.0;
    let mut checkpoints = expected.iter();
    for step in 1..=3600 {
        let path_force = if directed {
            steer::follow_path(&v, direction, 3.0, &path)
        } else {
            steer::stay_on_path(&v, 3.0, &path)
        };
        v.apply_steering_force(v.forward + path_force * 0.5, 1.0 / 60.0);
        if directed {
            if (v.position - points[0]).length() < path.radius {
                direction = 1.0;
            }
            if (v.position - points[15]).length() < path.radius {
                direction = -1.0;
            }
        }
        if step % 180 != 0 {
            continue;
        }
        let &(s, px, py, fx, fy, speed, dir) = checkpoints.next().unwrap();
        let got = [
            v.position.x,
            v.position.y,
            v.forward.x,
            v.forward.y,
            v.speed,
            direction,
        ];
        let want = [px, py, fx, fy, speed, dir];
        for (g, w) in got.iter().zip(want) {
            assert!(
                (f64::from(*g) - w).abs() < 1e-4,
                "step {s}: got {got:?}, want {want:?}"
            );
        }
    }
}

#[test]
fn follow_path_matches_cpp() {
    check(true, Vec2::new(-8.0, -3.0), &FOLLOW);
}

#[test]
fn stay_on_path_matches_cpp() {
    check(false, Vec2::new(4.0, 2.0), &STAY);
}
