#[test]
fn crossing_pedestrians_match_cpp() {
    let count = 8;
    let mut targets = Vec::new();
    let mut agents: Vec<Vehicle> = (0..count)
        .map(|i| {
            let angle = i as f32 * (TAU / count as f32);
            let start = Vec2::new(10.0 * angle.cos(), 10.0 * angle.sin());
            targets.push(-start);
            Vehicle {
                position: start,
                forward: (-start - start).normalize(),
                speed: 1.0,
                max_speed: 2.0,
                max_force: 8.0,
                radius: 0.5,
                ..Vehicle::default()
            }
        })
        .collect();
    let mut avoiding = 0;
    let mut checkpoints = CROSSING.iter();
    for step in 1..=900 {
        for i in 0..count {
            let others: Vec<&Vehicle> = agents
                .iter()
                .enumerate()
                .filter_map(|(j, a)| (j != i).then_some(a))
                .collect();
            let a = &agents[i];
            let avoidance = avoid_neighbors(a, 3.0, &others) * 10.0;
            let force = if avoidance != Vec2::ZERO {
                avoiding += 1;
                a.forward + avoidance
            } else {
                a.forward + steer::seek(a, targets[i])
            };
            agents[i].apply_steering_force(force, 1.0 / 60.0);
        }
        if step % 150 != 0 {
            continue;
        }
        for _ in 0..count {
            let &(s, i, px, py, fx, fy, speed, avoided) = checkpoints.next().unwrap();
            let a = &agents[i];
            let got = [
                a.position.x,
                a.position.y,
                a.forward.x,
                a.forward.y,
                a.speed,
            ];
            let want = [px, py, fx, fy, speed];
            for (g, w) in got.iter().zip(want) {
                assert!(
                    (f64::from(*g) - w).abs() < 1e-4,
                    "step {s} pedestrian {i}: got {got:?}, want {want:?}"
                );
            }
            assert_eq!(avoiding, avoided, "step {s}");
        }
    }
}
