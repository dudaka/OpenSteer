#[test]
fn avoidance_in_a_sphere_with_rocks_matches_cpp() {
    let obstacles = [
        Sphere::new(Vec3::ZERO, 15.0, SeenFrom::Inside),
        Sphere::new(Vec3::new(0.0, 2.0, 6.0), 2.0, SeenFrom::Outside),
        Sphere::new(Vec3::new(-6.0, -3.0, -2.0), 1.5, SeenFrom::Outside),
        Sphere::new(Vec3::new(7.0, 1.0, -6.0), 3.0, SeenFrom::Outside),
    ];
    let mut v = Vehicle {
        max_force: 5.0,
        max_speed: 3.0,
        ..Vehicle::default()
    };
    let (mut walk, mut rand) = (WanderState::default(), OracleRand(1));
    let mut avoiding = 0;
    let mut checkpoints = CPP.iter();
    for step in 1..=1800 {
        let mut force = avoid_obstacles(&v, 1.0, &obstacles);
        if force == Vec3::ZERO {
            let wander = steer::wander(&v, &mut walk, 1.0 / 60.0, &mut || rand.next01());
            force = v.forward + wander * 3.0;
        } else {
            avoiding += 1;
        }
        v.apply_steering_force(force, 1.0 / 60.0);
        if step == 1 || step % 90 == 0 {
            let (s, want, want_avoiding) = checkpoints
                .next()
                .expect("a checkpoint at step 1 and every 90");
            assert_eq!(*s, step);
            check(&v, step, want);
            assert_eq!(avoiding, *want_avoiding, "step {step}");
        }
    }
}
