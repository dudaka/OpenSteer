fn run(cpp: &[(u32, State)], force: impl Fn(&Vehicle) -> Vec3) {
    let mut v = Vehicle {
        max_force: 1.0,
        max_speed: 3.0,
        ..Vehicle::default()
    };
    let mut checkpoints = cpp.iter();
    for step in 1..=300 {
        v.apply_steering_force(force(&v), 1.0 / 60.0);
        if step == 1 || step % 30 == 0 {
            let (s, want) = checkpoints
                .next()
                .expect("a checkpoint at step 1 and every 30");
            assert_eq!(*s, step);
            check(&v, step, want);
        }
    }
}

#[test]
fn seek_matches_cpp() {
    run(&SEEK, |v| steer::seek(v, Vec3::new(6.0, 2.0, -4.0)));
}

#[test]
fn flee_matches_cpp() {
    run(&FLEE, |v| steer::flee(v, Vec3::new(1.0, -1.0, 1.0)));
}
