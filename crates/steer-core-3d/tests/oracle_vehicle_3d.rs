fn run(mut v: Vehicle, cpp: &[(u32, State)], force: impl Fn(&Vehicle) -> Vec3) {
    let mut checkpoints = cpp.iter();
    for step in 1..=600 {
        v.apply_steering_force(force(&v), 1.0 / 60.0);
        if step == 1 || step % 60 == 0 {
            let (s, want) = checkpoints
                .next()
                .expect("a checkpoint at step 1 and every 60");
            assert_eq!(*s, step);
            check(&v, step, want);
        }
    }
}

#[test]
fn climbing_turn_matches_cpp() {
    let v = Vehicle {
        speed: 1.5,
        max_force: 0.3,
        max_speed: 5.0,
        ..Vehicle::default()
    };
    run(v, &CLIMB, |_| Vec3::new(-2.0, 1.5, -3.0));
}

#[test]
fn banking_circle_matches_cpp() {
    let v = Vehicle {
        speed: 1.0,
        max_force: 1.0,
        max_speed: 2.0,
        banking: true,
        ..Vehicle::default()
    };
    run(v, &BANK, |v| v.side * 0.8 + v.forward * 0.1);
}
