fn run(cpp: &[(u32, State)], push: fn(&Vehicle) -> Vec3) {
    let mut v = Vehicle {
        max_force: 5.0,
        max_speed: 3.0,
        ..Vehicle::default()
    };
    let mut walk = WanderState::default();
    let mut rand = OracleRand(1);
    let mut checkpoints = cpp.iter();
    for step in 1..=600 {
        let wander = steer::wander(&v, &mut walk, 1.0 / 60.0, &mut || rand.next01());
        v.apply_steering_force(push(&v) + wander * 3.0, 1.0 / 60.0);
        if step == 1 || step % 60 == 0 {
            let (s, want) = checkpoints
                .next()
                .expect("a checkpoint at step 1 and every 60");
            assert_eq!(*s, step);
            check(&v, step, want);
        }
    }
}

