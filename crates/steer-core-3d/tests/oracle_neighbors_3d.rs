/// step, avoiding walker-steps so far
const AVOIDING: [(u32, u32); 7] = [
    (1, 0),
    (150, 150),
    (300, 949),
    (450, 1358),
    (600, 1358),
    (750, 1358),
    (900, 1358),
];

fn start(i: usize) -> Vec3 {
    let y = 1.0 - (i as f32 + 0.5) * (2.0 / COUNT as f32);
    let r = (1.0 - y * y).sqrt();
    let angle = i as f32 * 2.399_963_2;
    Vec3::new(r * angle.cos(), y, r * angle.sin()) * 10.0
}

#[test]
fn crossing_a_sphere_matches_cpp() {
    let mut walkers: Vec<Vehicle> = (0..COUNT)
        .map(|i| {
            let mut v = Vehicle {
                position: start(i),
                speed: 1.0,
                max_speed: 2.0,
                max_force: 8.0,
                ..Vehicle::default()
            };
            v.regenerate_basis((-start(i) - start(i)).normalize());
            v
        })
        .collect();
    let mut avoiding = 0;
    for step in 1..=900 {
        for i in 0..COUNT {
            let force = {
                let others: Vec<&Vehicle> = walkers
                    .iter()
                    .enumerate()
                    .filter_map(|(j, o)| (j != i).then_some(o))
                    .collect();
                let a = &walkers[i];
                let avoidance = avoid_neighbors(a, 3.0, &others) * 10.0;
                if avoidance != Vec3::ZERO {
                    avoiding += 1;
                    a.forward + avoidance
                } else {
                    a.forward + steer::seek(a, -start(i))
                }
            };
            walkers[i].apply_steering_force(force, 1.0 / 60.0);
        }
        for (s, i, want) in CPP.iter().filter(|c| c.0 == step) {
            assert_eq!(*s, step);
            check(&walkers[*i], step, want);
        }
        if let Some((_, a)) = AVOIDING.iter().find(|a| a.0 == step) {
            assert_eq!(avoiding, *a, "avoiding at step {step}");
        }
    }
}
