/// The oracle's 6x2 wall centered on (0, 1, 4), facing +z.
fn wall(seen_from: SeenFrom) -> Rectangle {
    Rectangle::new(
        6.0,
        2.0,
        Vec3::new(-1.0, 0.0, 0.0),
        Vec3::new(0.0, 1.0, 0.0),
        Vec3::new(0.0, 0.0, 1.0),
        Vec3::new(0.0, 1.0, 4.0),
        seen_from,
    )
}

/// Pedestrian.cpp's tilted 7x7 rectangle, moved to (3, 0, -3).
fn tilted() -> Rectangle {
    Rectangle::new(
        7.0,
        7.0,
        Vec3::new(0.0, 0.0, 1.0),
        Vec3::new(-1.0, 1.0, 0.0).normalize(),
        Vec3::new(1.0, 1.0, 0.0).normalize(),
        Vec3::new(3.0, 0.0, -3.0),
        SeenFrom::Both,
    )
}

fn v3(a: [f64; 3]) -> Vec3 {
    Vec3::new(a[0] as f32, a[1] as f32, a[2] as f32)
}

fn close(got: Vec3, want: [f64; 3]) -> bool {
    [got.x, got.y, got.z]
        .iter()
        .zip(want)
        .all(|(g, w)| (f64::from(*g) - w).abs() < 1e-4)
}

#[test]
fn every_pose_meets_the_rectangles_as_the_cpp() {
    for &(name, position, forward, want) in &HITS {
        let rect = match name {
            "outside" => wall(SeenFrom::Outside),
            "inside" => wall(SeenFrom::Inside),
            "both" => wall(SeenFrom::Both),
            _ => tilted(),
        };
        let mut v = Vehicle {
            position: v3(position),
            ..Vehicle::default()
        };
        v.regenerate_basis(v3(forward).normalize());
        let got = rect.intersect_path(&v);
        let ok = match (got, want) {
            (None, None) => true,
            (Some(g), Some((d, hint, surface))) => {
                (f64::from(g.distance) - d).abs() < 1e-4
                    && close(g.steer_hint, hint)
                    && close(g.surface_point, surface)
            }
            _ => false,
        };
        assert!(
            ok,
            "{name} {position:?} {forward:?}: got {got:?}, want {want:?}"
        );
    }
}

#[test]
fn seeking_across_two_walls_matches_the_cpp() {
    let obstacles = [wall(SeenFrom::Both), tilted()];
    let targets = [Vec3::new(0.5, 1.0, 10.0), Vec3::new(-0.5, 0.5, -8.0)];
    let mut v = Vehicle {
        max_force: 5.0,
        max_speed: 3.0,
        ..Vehicle::default()
    };
    let mut avoiding = 0;
    let mut checkpoints = WALLS.iter();
    for step in 1..=1800u32 {
        let target = targets[((step - 1) / 300 % 2) as usize];
        let mut force = avoid_obstacles(&v, 1.0, &obstacles);
        if force == Vec3::ZERO {
            force = steer::seek(&v, target);
        } else {
            avoiding += 1;
        }
        v.apply_steering_force(force, 1.0 / 60.0);
        if step == 1 || step % 45 == 0 {
            let (s, want, want_avoiding) = checkpoints
                .next()
                .expect("a checkpoint at step 1 and every 45");
            assert_eq!(*s, step);
            check(&v, step, want);
            assert_eq!(avoiding, *want_avoiding, "step {step}");
        }
    }
}
