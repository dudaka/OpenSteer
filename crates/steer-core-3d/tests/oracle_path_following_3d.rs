fn run(cpp: &[(u32, State, i32)], directed: bool, start: Vec3) {
    let path = Pathway::new(&EIGHT, 2.0, false);
    let mut v = Vehicle {
        position: start,
        max_speed: 2.0,
        max_force: 8.0,
        ..Vehicle::default()
    };
    let mut direction = 1.0;
    let mut checkpoints = cpp.iter();
    for step in 1..=3600 {
        let path_force = if directed {
            steer::follow_path(&v, direction, 3.0, &path)
        } else {
            steer::stay_on_path(&v, 3.0, &path)
        };
        v.apply_steering_force(v.forward + path_force * 0.5, 1.0 / 60.0);
        if directed {
            if (v.position - EIGHT[0]).length() < path.radius {
                direction = 1.0;
            }
            if (v.position - EIGHT[15]).length() < path.radius {
                direction = -1.0;
            }
        }
        if step == 1 || step % 180 == 0 {
            let (s, want, want_direction) = checkpoints
                .next()
                .expect("a checkpoint at step 1 and every 180");
            assert_eq!(*s, step);
            check(&v, step, want);
            assert_eq!(direction, *want_direction as f32, "step {step}");
        }
    }
}

#[test]
fn directed_path_following_matches_cpp() {
    run(&FOLLOW, true, Vec3::new(-8.0, 1.0, -3.0));
}

#[test]
fn stay_on_path_matches_cpp() {
    run(&STAY, false, Vec3::new(4.0, -1.0, 2.0));
}
