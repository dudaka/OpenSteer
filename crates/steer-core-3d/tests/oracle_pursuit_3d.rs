/// A pursuer at the origin facing +z at speed 1; a quarry at speed 2 one unit up, 5 away.
#[test]
fn every_table_cell_matches_cpp() {
    let offsets = [
        Vec3::new(0.0, 1.0, 5.0),
        Vec3::new(5.0, 1.0, 0.0),
        Vec3::new(0.0, 1.0, -5.0),
    ];
    let headings = [
        Vec3::new(0.0, 0.0, 1.0),
        Vec3::new(1.0, 0.0, 0.0),
        Vec3::new(0.0, 0.0, -1.0),
    ];
    let pursuer = Vehicle {
        speed: 1.0,
        ..at(0.0, 0.0, 0.0)
    };
    for (i, offset) in offsets.iter().enumerate() {
        for (j, heading) in headings.iter().enumerate() {
            let mut quarry = at(offset.x, offset.y, offset.z);
            quarry.regenerate_basis(*heading);
            quarry.speed = 2.0;
            let f = steer::pursuit(&pursuer, &quarry, 20.0);
            let want = CELLS[i * 3 + j];
            let got = [f.x, f.y, f.z];
            for (g, w) in got.iter().zip(want) {
                assert!(
                    (f64::from(*g) - w).abs() < 1e-4,
                    "cell {i} {j}: got {got:?}, want {want:?}"
                );
            }
        }
    }
}
