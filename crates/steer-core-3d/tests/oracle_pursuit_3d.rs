fn at(x: f32, y: f32, z: f32) -> Vehicle {
    Vehicle {
        position: Vec3::new(x, y, z),
        max_force: 5.0,
        max_speed: 3.0,
        ..Vehicle::default()
    }
}

/// Checks both vehicles at step 1 and every 60.
fn checkpoint(step: u32, a: (&Vehicle, &[(u32, State)]), b: (&Vehicle, &[(u32, State)])) {
    if step != 1 && !step.is_multiple_of(60) {
        return;
    }
    let index = (step / 60) as usize;
    for (v, cpp) in [a, b] {
        let (s, want) = &cpp[index];
        assert_eq!(*s, step);
        check(v, step, want);
    }
}

/// A pursuer from (8, 3, -6) chases a 3D wanderer (forward + 3 * wander), max prediction 20 s;
/// the wanderer moves first, as in `MpPlugIn::update`.
#[test]
fn pursuit_of_a_wanderer_matches_cpp() {
    let (mut wanderer, mut pursuer) = (at(0.0, 0.0, 0.0), at(8.0, 3.0, -6.0));
    let (mut walk, mut rand) = (WanderState::default(), OracleRand(1));
    for step in 1..=600 {
        let wander = steer::wander(&wanderer, &mut walk, 1.0 / 60.0, &mut || rand.next01());
        wanderer.apply_steering_force(wanderer.forward + wander * 3.0, 1.0 / 60.0);
        pursuer.apply_steering_force(steer::pursuit(&pursuer, &wanderer, 20.0), 1.0 / 60.0);
        checkpoint(step, (&pursuer, &PURSUER), (&wanderer, &WANDERER));
    }
}

/// An evader (max speed 2, prediction 2 s) and a hunter from (-5, -2, -5) pursuing it (20 s).
#[test]
fn evasion_from_a_hunter_matches_cpp() {
    let (mut evader, mut hunter) = (at(0.0, 0.0, 0.0), at(-5.0, -2.0, -5.0));
    evader.max_speed = 2.0;
    for step in 1..=600 {
        evader.apply_steering_force(steer::evasion(&evader, &hunter, 2.0), 1.0 / 60.0);
        hunter.apply_steering_force(steer::pursuit(&hunter, &evader, 20.0), 1.0 / 60.0);
        checkpoint(step, (&evader, &EVADER), (&hunter, &HUNTER));
    }
}

