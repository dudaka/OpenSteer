/// `Boid::reset`: max force 27, max speed 9, speed 2.7, a random heading, then a random spot in
/// a sphere of radius 20.
fn reset(rand: &mut OracleRand) -> Vehicle {
    let mut b = Vehicle {
        max_force: 27.0,
        max_speed: 9.0,
        banking: true,
        ..Vehicle::default()
    };
    b.speed = b.max_speed * 0.3;
    b.regenerate_basis(random_unit_vector(&mut || rand.next01()));
    b.position = random_vector_in_unit_sphere(&mut || rand.next01()) * 20.0;
    b
}

fn steer_to_flock(b: &Vehicle, others: &[&Vehicle]) -> Vec3 {
    let others = || others.iter().copied();
    separation(b, 5.0, -0.707, others()) * 12.0
        + alignment(b, 7.5, 0.7, others()) * 8.0
        + cohesion(b, 9.0, -0.15, others()) * 8.0
}

fn check_step(step: u32, boids: &[Vehicle], wraps: u32) {
    for (s, i, want) in CPP.iter().filter(|c| c.0 == step) {
        assert_eq!(*s, step);
        check(&boids[*i], step, want);
    }
    if let Some((_, w)) = WRAPS.iter().find(|w| w.0 == step) {
        assert_eq!(wraps, *w, "wraps at step {step}");
    }
}

#[test]
fn boids_match_cpp() {
    let mut rand = OracleRand(1);
    let mut boids: Vec<Vehicle> = (0..COUNT).map(|_| reset(&mut rand)).collect();
    let mut wraps = 0;
    check_step(0, &boids, wraps);
    for step in 1..=600 {
        for i in 0..COUNT {
            let force = {
                let others: Vec<&Vehicle> = boids
                    .iter()
                    .enumerate()
                    .filter_map(|(j, o)| (j != i).then_some(o))
                    .collect();
                steer_to_flock(&boids[i], &others)
            };
            let b = &mut boids[i];
            b.apply_steering_force(force, 1.0 / 60.0);
            if b.position.length() > 50.0 {
                b.position = b.position.spherical_wrap_around(Vec3::ZERO, 50.0);
                wraps += 1;
            }
        }
        check_step(step, &boids, wraps);
    }
}
