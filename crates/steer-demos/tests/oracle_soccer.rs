#[test]
fn a_minute_of_soccer_matches_cpp() {
    let mut game = Soccer::default();
    let mut checkpoints = MATCH.iter();
    for step in 1..=3600 {
        game.step(1.0 / 60.0);
        if step % 120 != 0 {
            continue;
        }
        let &(s, ball, score, players) = checkpoints.next().unwrap();
        assert_eq!(game.score(), score, "step {s}");
        let (b, first, last) = (game.ball(), game.player(0), game.player(15));
        let got = [
            b.position.x,
            b.position.y,
            b.speed,
            first.position.x,
            first.position.y,
            last.position.x,
            last.position.y,
        ];
        let want = [
            ball[0], ball[1], ball[2], players[0], players[1], players[2], players[3],
        ];
        for (g, w) in got.iter().zip(want) {
            assert!(
                (f64::from(*g) - w).abs() < 1e-4,
                "step {s}: got {got:?}, want {want:?}"
            );
        }
    }
}
