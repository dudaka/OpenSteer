fn seeker_evading_toward_home_matches_cpp() {
    check(at(36.0, 8.0, -0.6, 0.8), &NORTH);
}

#[test]
fn seeker_tagged_and_braking_matches_cpp() {
    check(at(-12.0, -36.0, 0.0, 1.0), &SOUTH);
}
