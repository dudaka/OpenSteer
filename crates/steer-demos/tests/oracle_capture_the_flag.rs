fn at(x: f32, y: f32, hx: f32, hy: f32) -> Vehicle {
    Vehicle {
        position: Vec2::new(x, y),
        forward: Vec2::new(hx, hy).normalize(),
        ..Vehicle::default()
    }
}

fn check(seeker: Vehicle, expected: &[Checkpoint]) {
    let rocks = [
        (10.0, 5.0, 2.0),
        (-8.0, 12.0, 3.0),
        (15.0, -10.0, 2.5),
        (-20.0, -5.0, 3.5),
        (25.0, 15.0, 2.0),
        (0.0, -18.0, 1.5),
        (-30.0, 20.0, 4.0),
        (30.0, -25.0, 3.0),
    ]
    .map(|(x, y, r)| Circle::new(Vec2::new(x, y), r, SeenFrom::Outside));
    let enemies = [
        at(20.0, 30.0, 1.0, -1.0),
        at(-25.0, -30.0, 1.0, 1.0),
        at(5.0, -35.0, -1.0, 1.0),
        at(-38.0, 5.0, 1.0, 0.0),
    ];
    let mut game = CaptureTheFlag::from_layout(seeker, enemies, rocks.to_vec());
    let mut checkpoints = expected.iter();
    for step in 1..=1200 {
        game.step(1.0 / 60.0);
        if step % 60 != 0 {
            continue;
        }
        let &(s, state, seeker, enemies) = checkpoints.next().unwrap();
        let want_state = [
            SeekerState::Running,
            SeekerState::Tagged,
            SeekerState::AtGoal,
        ];
        assert_eq!(game.state(), want_state[usize::from(state)], "step {s}");
        let v = game.seeker();
        let mut got = vec![
            v.position.x,
            v.position.y,
            v.forward.x,
            v.forward.y,
            v.speed,
        ];
        let mut want = seeker.to_vec();
        for (e, w) in game.enemies().iter().zip(enemies) {
            got.extend([e.position.x, e.position.y]);
            want.extend(w);
        }
        for (g, w) in got.iter().zip(&want) {
            assert!(
                (f64::from(*g) - w).abs() < 1e-4,
                "step {s}: got {got:?}, want {want:?}"
            );
        }
    }
}

