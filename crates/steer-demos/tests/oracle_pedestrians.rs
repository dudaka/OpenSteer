/// The oracle's `rand()` as `frandom01` sees it.
struct OracleRand(u32);

impl OracleRand {
    fn next01(&mut self) -> f32 {
        self.0 = self.0.wrapping_mul(1103515245).wrapping_add(12345);
        (self.0 & 0x7fff_ffff) as f32 / i32::MAX as f32
    }
}

#[test]
fn pedestrians_match_cpp() {
    let layout = Pedestrians::from_layout(Vec::new());
    let walkers = (0..10)
        .map(|i| {
            let a = i as f32 * 1.1;
            let v = Vehicle {
                position: layout.path().point_at(i as f32 * 25.0),
                forward: Vec2::new(a.cos(), a.sin()),
                ..Vehicle::default()
            };
            (v, if i % 2 == 0 { 1.0 } else { -1.0 })
        })
        .collect();
    let mut crowd = Pedestrians::from_layout(walkers);
    let mut rand = OracleRand(1);
    let mut checkpoints = CROWD.iter();
    for step in 1..=1800 {
        crowd.step(1.0 / 60.0, &mut || rand.next01());
        if step % 180 != 0 {
            continue;
        }
        for (v, direction) in crowd.walkers() {
            let &(s, i, want, dir, rocks, neighbors) = checkpoints.next().unwrap();
            let got = [
                v.position.x,
                v.position.y,
                v.forward.x,
                v.forward.y,
                v.speed,
            ];
            for (g, w) in got.iter().zip(want) {
                assert!(
                    (f64::from(*g) - w).abs() < 1e-4,
                    "step {s} pedestrian {i}: got {got:?}, want {want:?}"
                );
            }
            assert_eq!(f64::from(direction), dir, "step {s} pedestrian {i}");
            assert_eq!(
                (crowd.obstacle_steps, crowd.neighbor_steps),
                (rocks, neighbors),
                "step {s}"
            );
        }
    }
}
